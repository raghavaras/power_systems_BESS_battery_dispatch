# été 2025
def create_price_vector() -> np.ndarray:
    """Return hourly electricity prices in EUR/kWh (length 24)."""
    off_peak = 0.04870
    peak = 0.06405
    prices = [
        *(off_peak,) * 6,
        *(peak,) * 16,
        *(off_peak,) * 2,
    ]
    return np.array(prices, dtype=float)


